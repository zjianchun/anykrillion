def _pack_prompt(
    pid: str,
    pack: str,
    question: str,
    cat: str,
    timer: int,
    source: str,
    hints: List[str],
    rows: List[Tuple[str, float, str, List[str]]],
) -> dict:
    return {
        "id": pid,
        "pack": pack,
        "question": question,
        "categoryLabel": cat,
        "timerSeconds": timer,
        "sourceAttribution": source,
        "hints": hints,
        "answers": score_ranked_items(rows, higher_is_more_famous=True),
    }


